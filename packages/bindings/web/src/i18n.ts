const catalogues = new Map<string, Record<string, string>>([['en', EN], ['zh-tw', ZH_TW]])
const canonical = (locale: string): string => locale.trim().toLowerCase().replace(/_/g, '-')

/**
 * Add or extend a locale. Missing keys fall back along `zh-TW` to `zh` to `en`, so a partial catalogue is fine;
 * registering a name again merges into it (the later value wins). Values may use `{placeholders}`.
 */
export function registerLocale (locale: string, messages: WorkspaceMessages): void {
  if (typeof locale !== 'string' || !/^[a-z]{2,3}([-_][a-z0-9]{2,8})*$/i.test(locale.trim())) throw new TypeError('A locale is a BCP 47 style tag such as "ja" or "pt-BR"')
  if (messages === null || typeof messages !== 'object') throw new TypeError('Locale messages must be an object of strings')
  const clean: Record<string, string> = {}
  for (const [key, value] of Object.entries(messages)) {
    if (typeof value !== 'string') throw new TypeError(`Message ${JSON.stringify(key)} must be a string`)
    clean[key] = value
  }
  const name = canonical(locale)
  catalogues.set(name, name === 'en' ? { ...EN, ...clean } as Record<string, string> : { ...catalogues.get(name), ...clean })
}

/** Locales that can be selected now, in registration order. */
export function listLocales (): string[] { return [...catalogues.keys()] }

export function hasLocale (locale: string): boolean { return catalogues.has(canonical(locale)) }

/** The catalogue chain for a requested locale: exact tag, then its language, then English. */
function chain (locale: string): Array<Record<string, string>> {
  const name = canonical(locale), parts: Array<Record<string, string>> = []
  const exact = catalogues.get(name)
  if (exact !== undefined) parts.push(exact)
  const language = name.split('-')[0]
  const base = catalogues.get(language)
  if (base !== undefined && base !== exact) parts.push(base)
  // The package ships Traditional Chinese only: bare "zh", zh-HK and zh-MO use it, zh-CN/SG (Simplified) do not.
  if (parts.length === 0 && language === 'zh' && !/^zh-(cn|sg|hans)/.test(name)) parts.push(ZH_TW)
  if (!parts.includes(EN)) parts.push(EN)
  return parts
}

export type Translator = (key: WorkspaceMessageKey | (string & Record<never, never>), params?: Readonly<Record<string, string | number>>) => string

const humanize = (value: string): string => value.replace(/-/g, ' ')

/**
 * Translator for one locale. An unknown key returns the humanized tail of the key (`tool.fibonacci-fan` gives
 * `fibonacci fan`) so a missing translation degrades to readable text instead of a raw key.
 */
export function createTranslator (locale: string): Translator {
  const catalogs = chain(locale)
  return (key, params) => {
    let text: string | undefined
    for (const catalog of catalogs) { text = catalog[key]; if (text !== undefined) break }
    text ??= humanize(key.slice(key.lastIndexOf('.') + 1))
    if (params === undefined) return text
    return text.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match)
  }
}

/** Resolve a requested tag to the nearest locale that has a catalogue ('en' when none). */
export function resolveLocale (locale: string | undefined): string {
  if (locale === undefined) return 'en'
  const name = canonical(locale)
  if (catalogues.has(name)) return name
  const language = name.split('-')[0]
  if (catalogues.has(language)) return language
  if (language === 'zh' && !/^zh-(cn|sg|hans)/.test(name)) return 'zh-tw'
  return 'en'
}
