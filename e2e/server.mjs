// Static file server for the browser tests: serves frontend/super-chart (the
// built dist/ and these pages) and the klinecharts versions under
// e2e/node_modules. Local only; started by playwright.config.ts.
import { createServer } from 'node:http'
import { existsSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { dirname, extname, join, normalize, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { runInNewContext } from 'node:vm'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const port = Number(process.env.SC_E2E_PORT ?? 4179)
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.cjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.svg': 'image/svg+xml'
}

/**
 * klinecharts <version> from e2e/node_modules/kc-<version> (an npm alias).
 * /e2e/kc/<version>/umd.js is its UMD build (the `klinecharts` global).
 * /e2e/kc/<version>/esm.js is its ES build, what bundlers load. 9.1.1 ships
 * no ES build, so it gets a module that runs the UMD build as CommonJS and
 * re-exports every name that build defines (read here, in a sandbox).
 */
async function klinecharts (version, kind) {
  const dist = join(root, 'e2e', 'node_modules', `kc-${version.split('.').join('-')}`, 'dist')
  const umd = [join(dist, 'umd', 'klinecharts.js'), join(dist, 'klinecharts.js')].find(f => existsSync(f))
  if (umd === undefined) return null
  if (kind === 'umd') return await readFile(umd)
  if (existsSync(join(dist, 'index.esm.js'))) return await readFile(join(dist, 'index.esm.js'))
  const code = await readFile(umd, 'utf8')
  const probe = { exports: {} }
  runInNewContext(code, { module: probe, exports: probe.exports })
  return [
    `// klinecharts ${version} has no ES build: its UMD build, run as CommonJS (generated by e2e/server.mjs).`,
    'const module = { exports: {} }',
    `;(function (module, exports) {\n${code}\n}).call(globalThis, module, module.exports)`,
    'const K = module.exports',
    'export default K',
    `export const { ${Object.keys(probe.exports).join(', ')} } = K`,
    ''
  ].join('\n')
}

createServer(async (req, res) => {
  const path = normalize(decodeURIComponent(new URL(req.url ?? '/', 'http://x').pathname))
  const kc = /^[\\/]e2e[\\/]kc[\\/](\d+\.\d+\.\d+)[\\/](esm|umd)\.js$/.exec(path)
  if (kc !== null) {
    const body = await klinecharts(kc[1], kc[2]).catch(e => { console.error(e); return null })
    if (body === null) {
      res.writeHead(404).end(`no klinecharts ${kc[1]} under e2e/node_modules/kc-${kc[1].split('.').join('-')}`)
      return
    }
    res.writeHead(200, { 'content-type': TYPES['.js'], 'cache-control': 'no-store' })
    res.end(body)
    return
  }
  const file = join(root, path)
  if (file !== root && !file.startsWith(root + sep)) {
    res.writeHead(403).end()
    return
  }
  try {
    const body = await readFile(file)
    res.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream', 'cache-control': 'no-store' })
    res.end(body)
  } catch {
    res.writeHead(404).end(`not found: ${path}`)
  }
}).listen(port, '127.0.0.1', () => { console.log(`super-chart e2e server on http://127.0.0.1:${port}`) })
